const char* UIBmp(const char* uiBmpName)
{
	if (g_skinMgr.GetNumSkin() && g_skinMgr.GetCurrentSkinNum() != -1 && g_modeMgr.GetGameMode()) {
		std::string skinFolder = g_skinMgr.GetSkinCurrentFolderName();

		static std::string skinRName;
		std::string tmpName = uiBmpName;

		skinRName = "";
		for (int i = 0; i < tmpName.size() - 15; ++i) {
			skinRName += tmpName[15 + i];
		}

		g_skinMgr.ExtractFilesIfZipSkin();
		skinRName = skinFolder + skinRName;
		tmpName = skinRName;
		if (g_resMgr().IsExist(tmpName.c_str()))
			return skinRName.c_str();
	}

	if (g_serviceType == ServiceKorea)
		return uiBmpName;
	if (g_resMgr().IsExist(g_language->LanguageFile(uiBmpName)))
		return g_language->LanguageFile(uiBmpName);

	static std::string rName;
	std::string tmpName = uiBmpName;

	rName = "";
	for (int i = 0; i < tmpName.size() - 15; ++i) {
		rName += tmpName[15 + i];
	}
	rName = "UI\\" + rName;
	tmpName = rName;
	if (g_resMgr().IsExist(tmpName.c_str()))
		return rName.c_str();
	return uiBmpName;
}




char* DataTxtDecode(char* str)
{
	if (g_serviceType == ServiceKorea) {
		BYTE c;
		int len = strlen(str);
		for (int i = 0; i < len; ++i) {
			c = str[i];

			if (c >= 'a' && c <= 'z')
				c = 'a' + 'z' - c;
			if (c >= 'A' && c <= 'Z')
				c = 'A' + 'Z' - c;
			else {
				if (c >= 0xb0 && c <= 0xbf)
					c = 0xb0 + (0xbf - c);
			}
			str[i] = c;
		}
	}
	return str;
}
